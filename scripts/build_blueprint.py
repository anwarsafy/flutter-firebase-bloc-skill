import markdown
from pygments.formatters import HtmlFormatter

ROOT = Path(__file__).resolve().parent.parent
SKILL = ROOT / "skills" / "flutter-firebase-bloc"
OUT = ROOT / "docs" / "Flutter_Firebase_BLoC_Blueprint_ULTIMATE.html"

REFERENCES = [
    ("architecture", "Architecture, Data & DI", "architecture-and-di.md"),
    ("auth", "Auth & Security Rules", "auth-and-security.md"),
    ("bloc", "BLoC, Errors & l10n", "bloc-errors-l10n.md"),
    ("notifications", "Notifications, Functions & Router", "notifications-and-links.md"),
    ("production", "Flavors, Perf, RC & CI/CD", "flavors-perf-rc-cicd.md"),
]
TEMPLATE_LANG = {".yaml": "yaml", ".yml": "yaml", ".json": "json", ".arb": "json", ".plist": "xml", ".firebaserc": "json"}


def render(md_text: str) -> str:
    md_text = re.sub(r"\A---\n.*?\n---\n", "", md_text, flags=re.S)  # drop YAML front matter
    return markdown.markdown(
        md_text,
        extensions=["fenced_code", "tables", "codehilite", "sane_lists"],
        extension_configs={"codehilite": {"guess_lang": False, "css_class": "hl"}},
    )


def version() -> str:
    m = re.search(r'"version":\s*"([^"]+)"', (ROOT / ".claude-plugin" / "plugin.json").read_text())
    return m.group(1) if m else "dev"


def templates_md() -> str:
    parts = ["# Drop-In Templates\n", "Copy these files into your project as described in the Canonical Project Layout.\n"]
    for f in sorted((SKILL / "templates").iterdir(), key=lambda p: p.name.lower()):
        lang = TEMPLATE_LANG.get(f.suffix or f.name, "text")
        parts.append(f"## `{f.name}`\n```{lang}\n{f.read_text().rstrip()}\n```\n")
    return "\n".join(parts)


def main() -> None:
    sections = [("overview", "SKILL.md — Rules & Decisions", (SKILL / "SKILL.md").read_text())]
    sections += [(sid, title, (SKILL / "references" / name).read_text()) for sid, title, name in REFERENCES]
    sections.append(("templates", "Templates", templates_md()))
    sections.append(("install", "Install Anywhere", (SKILL / "INSTALL.md").read_text()))

    nav, body = [], []
    for i, (sid, title, text) in enumerate(sections):
        active = " active" if i == 0 else ""
        nav.append(f'<button class="nav-item{active}" data-target="{sid}"><span class="nav-dot"></span>{html.escape(title)}</button>')
        body.append(f'<section id="{sid}" class="section{active}">{render(text)}</section>')

    css = HtmlFormatter(style="monokai").get_style_defs(".hl")
    page = TEMPLATE.format(
        version=version(), css=css, nav="\n    ".join(nav), body="\n".join(body)
    )
    OUT.write_text(page, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(page):,} bytes)")


