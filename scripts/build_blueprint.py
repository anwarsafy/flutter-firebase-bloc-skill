"""Generate docs/Flutter_Firebase_BLoC_Blueprint_ULTIMATE.html from the skill's Markdown.

The blueprint is a rendered view of SKILL.md, references/*.md and templates/*, so it can
never drift from the code the AI agents actually load. CI runs this script and fails if the
committed HTML differs (`git diff --exit-code docs/`).

Usage: pip install markdown pygments && python3 scripts/build_blueprint.py
"""
from __future__ import annotations

import html
import re
